"""Carrying files as text and checking they arrived whole -- offline, no model, standard library only.

    python ad-hoc/workbench/test_text_transfer.py

The files here are generated bytes (and a small .xlsx written with openpyxl); nothing real is read.
"""
from __future__ import annotations

import hashlib
import io
import json
import os
import sys
import tarfile
import tempfile
import unittest
import zlib
import base64
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import text_transfer as X  # noqa: E402


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


class World:
    def __init__(self, size=300_000):
        self.tmp = Path(tempfile.mkdtemp(prefix="xfer_"))
        rng = __import__("random").Random(7)
        self.book = self.tmp / "src" / "Book.xlsx"
        self.book.parent.mkdir()
        self.book.write_bytes(bytes(rng.getrandbits(8) for _ in range(size)))        # incompressible, like a zipped workbook
        self.folder = self.tmp / "src" / "run_1"
        (self.folder / "evidence").mkdir(parents=True)
        (self.folder / "results.yml").write_text("AR: {final: '应收账款余额100.0万元'}\n", encoding="utf-8")
        (self.folder / "evidence" / "AR.json").write_text(json.dumps({"a": 1}), encoding="utf-8")

    def encode(self, chunk_kb=50, paths=None):
        out = self.tmp / "text"
        return out, X.encode([str(p) for p in (paths or [self.book, self.folder])], out, chunk_kb)


class RoundTrip(unittest.TestCase):
    def test_files_and_folders_arrive_with_the_same_bytes_and_the_same_hashes(self):
        w = World()
        out, info = w.encode()
        self.assertGreater(info["parts"], 3)
        self.assertEqual(info["files"], 3)
        got = w.tmp / "got"
        r = X.decode([str(out)], got)
        self.assertTrue(r["ok"], r)
        self.assertEqual(sha(got / "Book.xlsx"), sha(w.book))
        self.assertEqual((got / "run_1" / "results.yml").read_text(encoding="utf-8"), (w.folder / "results.yml").read_text(encoding="utf-8"))
        self.assertTrue((got / "run_1" / "evidence" / "AR.json").exists())
        self.assertEqual(r["sha256"]["Book.xlsx"], sha(w.book))

    def test_one_part_when_the_chunk_size_is_zero(self):
        w = World(size=20_000)
        out, info = w.encode(chunk_kb=0)
        self.assertEqual(info["parts"], 1)
        self.assertTrue(X.decode([str(out)], w.tmp / "got")["ok"])

    def test_parts_pasted_into_markdown_with_prose_fences_quotes_and_in_any_order_still_decode(self):
        w = World(size=60_000)
        out, info = w.encode(chunk_kb=20)
        parts = sorted(out.glob("part-*.txt"))
        self.assertGreater(len(parts), 2)
        md = w.tmp / "paste"
        md.mkdir()
        # part 3 first, each wrapped differently: a fence, a quote prefix, trailing spaces, prose before and after
        chunks = [p.read_text(encoding="ascii") for p in parts]
        (md / "a.md").write_text("Here is the third part.\n\n```\n" + chunks[2] + "```\n\nand some more prose\n", encoding="utf-8")
        (md / "b.md").write_text("\n".join("> " + line + "   " for line in chunks[0].splitlines()) + "\n\n" + "".join(chunks[1:2]) + "\nthe end\n", encoding="utf-8")
        if len(chunks) > 3:
            (md / "c.md").write_text("\n".join(chunks[3:]), encoding="utf-8")
        r = X.decode([str(md)], w.tmp / "got")
        self.assertTrue(r["ok"], r)
        self.assertEqual(sha(w.tmp / "got" / "Book.xlsx"), sha(w.book))


class Damage(unittest.TestCase):
    def test_a_damaged_part_is_named_and_nothing_is_written(self):
        w = World(size=60_000)
        out, _ = w.encode(chunk_kb=20)
        victim = sorted(out.glob("part-*.txt"))[1]
        lines = victim.read_text(encoding="ascii").splitlines()
        lines[3] = lines[3][:10] + ("A" if lines[3][10] != "A" else "B") + lines[3][11:]
        victim.write_text("\n".join(lines) + "\n", encoding="ascii")
        got = w.tmp / "got"
        r = X.decode([str(out)], got)
        self.assertFalse(r["ok"])
        self.assertTrue(any("part 2/" in p and "damaged" in p for p in r["problems"]), r["problems"])
        self.assertFalse(got.exists())

    def test_a_missing_part_is_named(self):
        w = World(size=60_000)
        out, info = w.encode(chunk_kb=20)
        sorted(out.glob("part-*.txt"))[2].unlink()
        r = X.decode([str(out)], w.tmp / "got")
        self.assertFalse(r["ok"])
        self.assertTrue(any("missing part(s): 3" in p for p in r["problems"]), r["problems"])

    def test_text_cut_off_before_the_crc_line_is_reported_not_guessed(self):
        w = World(size=30_000)
        out, _ = w.encode(chunk_kb=0)
        text = (out / "part-001.txt").read_text(encoding="ascii").splitlines()
        (out / "part-001.txt").write_text("\n".join(text[:-1]) + "\n", encoding="ascii")
        r = X.decode([str(out)], w.tmp / "got")
        self.assertFalse(r["ok"])
        self.assertTrue(any("CRC line is missing" in p for p in r["problems"]), r["problems"])

    def test_nothing_that_looks_like_an_archive_says_so(self):
        d = Path(tempfile.mkdtemp())
        (d / "notes.md").write_text("no parts in here\n", encoding="utf-8")
        r = X.decode([str(d)], d / "out")
        self.assertFalse(r["ok"])
        self.assertIn("no part of an archive", r["problems"][0])

    def test_parts_of_two_archives_are_not_mixed(self):
        a, b = World(size=30_000), World(size=31_000)
        oa, _ = a.encode(chunk_kb=10)
        ob, _ = b.encode(chunk_kb=10)
        mixed = Path(tempfile.mkdtemp())
        (mixed / "1.txt").write_text((oa / "part-001.txt").read_text(encoding="ascii"), encoding="utf-8")
        (mixed / "2.txt").write_text((ob / "part-002.txt").read_text(encoding="ascii"), encoding="utf-8")
        r = X.decode([str(mixed)], mixed / "out")
        self.assertFalse(r["ok"])
        self.assertTrue(any("another archive" in p for p in r["problems"]), r["problems"])

    def test_a_file_that_changed_inside_a_whole_archive_is_caught_by_its_own_hash(self):
        w = World(size=10_000)
        files = X.collect([str(w.book)])
        packed, listing = X.build_archive(files)
        raw = zlib.decompress(packed)
        buf = io.BytesIO()
        with tarfile.open(fileobj=io.BytesIO(raw)) as src, tarfile.open(fileobj=buf, mode="w") as dst:
            for m in src.getmembers():
                data = src.extractfile(m).read()
                if m.name == "Book.xlsx":
                    data = b"x" + data[1:]
                info = tarfile.TarInfo(m.name)
                info.size = len(data)
                dst.addfile(info, io.BytesIO(data))
        forged = zlib.compress(buf.getvalue(), 9)
        text = base64.b64encode(forged).decode("ascii")
        ident = hashlib.sha256(forged).hexdigest()[:16]
        lines = [text[i:i + 76] for i in range(0, len(text), 76)]
        crc = f"{zlib.crc32(text.encode('ascii')) & 0xffffffff:08x}"
        d = Path(tempfile.mkdtemp())
        (d / "p.txt").write_text("\n".join([f"FDDXFER 1 part 1/1 {ident}", *lines, f"CRC {crc}"]) + "\n", encoding="ascii")
        r = X.decode([str(d)], d / "out")
        self.assertFalse(r["ok"])
        self.assertTrue(any("Book.xlsx: arrived changed" in p for p in r["problems"]), r)

    def test_an_archive_that_names_a_path_outside_the_output_folder_is_refused(self):
        buf = io.BytesIO()
        manifest = json.dumps({"version": 1, "files": {"../escape.txt": {"bytes": 1, "sha256": hashlib.sha256(b"x").hexdigest()}}}).encode()
        with tarfile.open(fileobj=buf, mode="w") as tar:
            for name, data in ((X.MANIFEST_NAME, manifest), ("../escape.txt", b"x")):
                info = tarfile.TarInfo(name)
                info.size = len(data)
                tar.addfile(info, io.BytesIO(data))
        packed = zlib.compress(buf.getvalue(), 9)
        text = base64.b64encode(packed).decode("ascii")
        lines = [text[i:i + 76] for i in range(0, len(text), 76)]
        crc = f"{zlib.crc32(text.encode('ascii')) & 0xffffffff:08x}"
        d = Path(tempfile.mkdtemp())
        (d / "p.txt").write_text("\n".join([f"FDDXFER 1 part 1/1 {hashlib.sha256(packed).hexdigest()[:16]}", *lines, f"CRC {crc}"]) + "\n", encoding="ascii")
        with self.assertRaises(SystemExit) as caught:
            X.decode([str(d)], d / "out")
        self.assertIn("outside the output folder", str(caught.exception))
        self.assertFalse((d / "escape.txt").exists())

    def test_an_output_folder_with_something_in_it_is_not_written_into(self):
        w = World(size=10_000)
        out, _ = w.encode(chunk_kb=0)
        got = w.tmp / "got"
        got.mkdir()
        (got / "mine.txt").write_text("keep", encoding="utf-8")
        r = X.decode([str(out)], got)
        self.assertFalse(r["ok"])
        self.assertEqual((got / "mine.txt").read_text(encoding="utf-8"), "keep")
        self.assertFalse((got / "Book.xlsx").exists())

    def test_two_inputs_with_the_same_name_are_refused_at_encoding(self):
        w = World(size=1000)
        other = w.tmp / "other" / "Book.xlsx"
        other.parent.mkdir()
        other.write_bytes(b"x")
        with self.assertRaises(SystemExit):
            X.encode([str(w.book), str(other)], w.tmp / "text", 0)


class Command(unittest.TestCase):
    def test_the_command_line_round_trips_and_prints_no_file_names(self):
        import contextlib
        w = World(size=30_000)
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            self.assertEqual(X.main(["encode", str(w.book), "--out", str(w.tmp / "t"), "--chunk-kb", "10"]), 0)
            self.assertEqual(X.main(["decode", str(w.tmp / "t"), "--out", str(w.tmp / "g")]), 0)
        text = buf.getvalue()
        self.assertIn("every file's sha256 matches", text)
        self.assertNotIn("Book.xlsx", text)
        self.assertEqual(sha(w.tmp / "g" / "Book.xlsx"), sha(w.book))


if __name__ == "__main__":
    unittest.main(verbosity=2)
